"""Clipboard watcher: notices *that* the clipboard changed, never *what* it holds.

Privacy (todo #34): the watcher polls
``NSPasteboard.generalPasteboard().changeCount()`` and, on a change, reads
only the pasteboard's type list to classify the copy as ``text``, ``url``,
``image``, ``file`` or ``other``. It never calls ``stringForType_``,
``dataForType_`` or any other accessor that returns the copied data.
Copies marked concealed or transient (password managers set
``org.nspasteboard.ConcealedType``/``TransientType``) are not reported at
all.

Each change becomes ``ContextEvent(event_type="clipboard_changed",
app_name=<frontmost app or None>, metadata={"app", "kind"})``.

Threading, measured with a probe on 2026-11-09 (pyobjc in a daemon-like
process whose main thread is blocked, no run loop):

* ``changeCount()`` works from a background thread: a change made by
  another process was seen without any run loop.
* ``NSWorkspace.frontmostApplication()`` is stale off the main run loop
  (it kept returning the app that was frontmost when the process started,
  after a real switch to Finder). The same reason the app listener runs a
  helper subprocess (DONE.md #3). So the frontmost app is resolved with
  ``lsappinfo front`` (one short subprocess per clipboard change, not per
  poll), which was correct in the same probe. The friction detector does
  not rely on this field: it attributes a copy to the most recent
  ``app_activated`` it saw, so its copy -> switch ordering comes from one
  source.
"""

from __future__ import annotations

import logging
import subprocess
import threading
from typing import Any, Callable, Optional

from .event_bus import ContextEvent, EventBus

logger = logging.getLogger(__name__)

DEFAULT_POLL_INTERVAL = 1.0  # seconds

# Marker types from nspasteboard.org: never report these copies.
_SKIP_TYPES = frozenset({
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
})

# Type identifier -> kind, checked in order (a copied file also carries text).
_KIND_RULES: tuple[tuple[str, tuple[str, ...]], ...] = (
    ("file", ("public.file-url", "NSFilenamesPboardType")),
    ("image", ("public.png", "public.tiff", "public.jpeg", "com.adobe.pdf")),
    ("url", ("public.url", "NSURLPboardType")),
    ("text", ("public.utf8-plain-text", "public.plain-text", "NSStringPboardType",
              "public.rtf", "public.html")),
)


def classify_types(types: Optional[list[str]]) -> Optional[str]:
    """Map a pasteboard type list to a kind; ``None`` means don't report."""
    names = [str(t) for t in (types or [])]
    if any(t in _SKIP_TYPES for t in names):
        return None
    for kind, markers in _KIND_RULES:
        if any(t in markers for t in names):
            return kind
    return "other" if names else None


def _lsappinfo_front() -> Optional[str]:
    """Name of the frontmost app via ``lsappinfo`` (works off the main thread)."""
    try:
        asn = subprocess.run(
            ["lsappinfo", "front"], capture_output=True, text=True, timeout=2.0,
        ).stdout.strip()
        if not asn:
            return None
        out = subprocess.run(
            ["lsappinfo", "info", "-only", "name", asn],
            capture_output=True, text=True, timeout=2.0,
        ).stdout.strip()
    except (OSError, subprocess.SubprocessError):
        return None
    # Output looks like: "LSDisplayName"="Finder"
    _, _, value = out.partition("=")
    value = value.strip().strip('"')
    return value or None


def _general_pasteboard() -> Any:
    from AppKit import NSPasteboard  # type: ignore[import-not-found]

    return NSPasteboard.generalPasteboard()


class ClipboardWatcher:
    """Poll the general pasteboard's ``changeCount`` and emit ``clipboard_changed``."""

    def __init__(
        self,
        bus: EventBus,
        *,
        poll_interval: float = DEFAULT_POLL_INTERVAL,
        pasteboard_factory: Callable[[], Any] = _general_pasteboard,
        frontmost_app: Callable[[], Optional[str]] = _lsappinfo_front,
    ) -> None:
        self._bus = bus
        self._poll_interval = poll_interval
        self._pasteboard_factory = pasteboard_factory
        self._frontmost_app = frontmost_app
        self._pasteboard: Any = None
        self._last_count: Optional[int] = None
        self._thread: Optional[threading.Thread] = None
        self._stop_event = threading.Event()

    def start(self) -> None:
        if self._thread is not None:
            return
        try:
            self._pasteboard = self._pasteboard_factory()
            self._last_count = int(self._pasteboard.changeCount())
        except Exception:
            logger.exception("Clipboard watcher could not open the pasteboard; idle")
            return
        self._stop_event.clear()
        self._thread = threading.Thread(
            target=self._run, name="ClipboardWatcher", daemon=True
        )
        self._thread.start()
        logger.info("ClipboardWatcher started (changeCount=%s)", self._last_count)

    def stop(self) -> None:
        self._stop_event.set()
        thread = self._thread
        self._thread = None
        if thread is not None:
            thread.join(timeout=self._poll_interval + 1.0)

    def _run(self) -> None:
        while not self._stop_event.wait(self._poll_interval):
            try:
                event = self.poll_once()
            except Exception:
                logger.exception("clipboard poll failed; will retry")
                continue
            if event is None:
                continue
            try:
                self._bus.push_threadsafe(event)
            except Exception:  # pragma: no cover - loop not bound or shutting down
                logger.exception("Failed to push clipboard_changed event")

    def poll_once(self) -> Optional[ContextEvent]:
        """Check ``changeCount``; return an event for a reportable change."""
        if self._pasteboard is None:
            self._pasteboard = self._pasteboard_factory()
        count = int(self._pasteboard.changeCount())
        if self._last_count is None:
            self._last_count = count
            return None
        if count == self._last_count:
            return None
        self._last_count = count
        # Type identifiers only; the copied data is never requested.
        kind = classify_types(list(self._pasteboard.types() or []))
        if kind is None:
            return None
        app = self._frontmost_app()
        return ContextEvent(
            event_type="clipboard_changed",
            app_name=app,
            metadata={"app": app, "kind": kind},
        )


__all__ = ["ClipboardWatcher", "classify_types"]
